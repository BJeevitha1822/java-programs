public class DataTypes {
    public static void main(String[] args) {

        // Integer data types
        byte age = 20;       //SMALL WHOLE NUMBER 
        short year = 2026;   //WHOLE NUMBER
        int population = 100000;    //COMMON WHOLE NUMBER
        long distance = 10000000000L;    //LONG WHOLE NUMBER  "LONG USE L"

        // Decimal data types
        float percentage = 85.5f;  //FLOAT USE f
        double cgpa = 8.69;      //More precise decimal

        // Character data type
        char grade = 'A';

        // Boolean data type
        boolean isStudent = true;

        // String
        String name = "Jeevitha";

        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
        System.out.println("Year: " + year);
        System.out.println("Population: " + population);
        System.out.println("Distance: " + distance);
        System.out.println("Percentage: " + percentage);
        System.out.println("CGPA: " + cgpa);
        System.out.println("Grade: " + grade);
        System.out.println("Student: " + isStudent);
    }
}
