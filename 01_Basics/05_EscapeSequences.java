public class Main{
    public static void main(String[] args) {

        System.out.println("Hello\nWorld");       //NEW LINE  \n
        System.out.println("Java\tProgramming");     //GAP  \t
        System.out.println('\'');       //SINGLE QUOTE  '\''     '\' 
        System.out.println("He said, \"Java is easy!\""); //DOUBLE QUOTE \" \"
        System.out.println("This is a backslash: \\");  //PRINTS \ FOR \\
    }
}
